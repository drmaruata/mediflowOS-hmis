"""Append the tenant_id backfill step to each generated expand migration.

The 0002 migrations created by makemigrations add tenant_id as nullable so the
NOT NULL constraint is not created in the same step as the backfill. This
inserts the RunPython that fills it in, after the column exists and before the
0003 contract migration runs.

The parent chains below are the real ownership edges in the models; each one
lets the owning tenant be derived from a row that is already tenant-scoped.
"""
